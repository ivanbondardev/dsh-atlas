  const dicts = { uk, en }
  const initial = util.storage.get('lang', null) ?? ((navigator.language || '').toLowerCase().startsWith('uk') ? 'uk' : 'en')

  const i18n = DSHMap.i18n = {
    lang: dicts[initial] ? initial : 'uk',
    locale() { return this.lang === 'uk' ? 'uk-UA' : 'en-GB' },
    t(key, vars) {
      let s = dicts[this.lang][key] ?? dicts.en[key] ?? key
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
      return s
    },
    /** Pick a localized field from an { en, uk } record. */
    pick(rec) {
      if (!rec) return ''
      if (typeof rec === 'string') return rec
      return rec[this.lang] ?? rec.en ?? Object.values(rec)[0]
    },
    /** Plural with the count: tn('lines', 5) → "5 рядків" via n.lines.{one,few,many} (uk) or {one,other} (en). */
    tn(base, n) {
      const form = DSHMap.fmt.plural(n, { one: 'one', few: 'few', many: 'many', other: 'other' })
      return this.t(`n.${base}.${form}`, { n: DSHMap.fmt.num(n) })
    },
    /** Localize the static page shell (title, description, boot spinner). */
    applyPage() {
      document.title = this.t('brand')
      document.querySelector('meta[name="description"]')?.setAttribute('content', this.t('page.description'))
      const boot = document.getElementById('boot-text')
      if (boot) boot.textContent = this.t('page.loading')
    },
    /** Merge view-owned dictionaries: extend({ uk: {...}, en: {...} }). */
    extend(more) {
      for (const [lang, d] of Object.entries(more)) Object.assign(dicts[lang] ??= {}, d)
    },
    set(lang) {
      if (!dicts[lang] || lang === this.lang) return
      this.lang = lang
      util.storage.set('lang', lang)
      document.documentElement.lang = lang
      this.applyPage()
      DSHMap.emit('lang', lang)
    },
  }
  document.documentElement.lang = i18n.lang
  DSHMap.t = i18n.t.bind(i18n)
  i18n.applyPage()
